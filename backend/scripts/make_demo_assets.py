"""Generate the sample photos offered to judges and visitors in demo mode.

Visitors have no medicine strip at hand, so the demo lets them "take" a photo
by picking one of these. They form a story: reference strips, the first dose,
the next dose, an extra pill, a blurry shot, a glare shot, the wrong strip and
an unregistered strip. Replace any file with a real photo of the same scene
(keep the file name) and re-run nothing: the manifest stays valid.

    python scripts/make_demo_assets.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import cv2 as cv

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from pillcheck import synth  # noqa: E402

OUT = Path(__file__).resolve().parent.parent / "demo_assets"

TELMI = synth.StripSpec(name="TELMISARTAN 40mg", seed=1)
METF = synth.StripSpec(name="METFORMIN 500mg", rows=3, cols=4, seed=7, pill_colour=(150, 210, 160), ink_colour=(30, 120, 40))
OTHER = synth.StripSpec(name="ATORVASTATIN 10", seed=33, rows=1, cols=6)

MEDICATIONS = [
    {"key": "telmi", "name": "Telmisartan", "strength": "40 mg", "instructions": "After breakfast and dinner",
     "schedule": [{"time": "09:00", "pills": 1}, {"time": "21:00", "pills": 1}], "reference": "telmisartan_reference.jpg"},
    {"key": "metf", "name": "Metformin", "strength": "500 mg", "instructions": "With meals",
     "schedule": [{"time": "08:30", "pills": 1}, {"time": "20:30", "pills": 1}], "reference": "metformin_reference.jpg"},
]

# (file, spec, popped, seed, kwargs, sample metadata)
SHOTS = [
    ("telmisartan_reference.jpg", TELMI, set(), 11, dict(difficulty=0.1), None),
    ("metformin_reference.jpg", METF, set(), 11, dict(difficulty=0.1), None),
    ("telmisartan_dose1.jpg", TELMI, {0}, 21, dict(difficulty=0.6),
     {"medication": "telmi", "title": "Telmisartan, after the 9 AM dose", "hint": "One tablet removed. Expect: dose recorded."}),
    ("telmisartan_dose2.jpg", TELMI, {0, 1}, 22, dict(difficulty=0.7),
     {"medication": "telmi", "title": "Telmisartan, after the 9 PM dose", "hint": "A second tablet removed. In the morning this is an extra pill; in the evening it is the 9 PM dose."}),
    ("telmisartan_extra.jpg", TELMI, {0, 1, 2}, 23, dict(difficulty=0.6),
     {"medication": "telmi", "title": "Telmisartan, one tablet too many", "hint": "More removed than scheduled. Expect: urgent caregiver alert."}),
    ("telmisartan_blurry.jpg", TELMI, {0}, 24, dict(difficulty=0.5, blur_sigma=4.0),
     {"medication": "telmi", "title": "Telmisartan, blurry photo", "hint": "Expect: a retake request with instructions."}),
    ("telmisartan_glare.jpg", TELMI, {0}, 25, dict(difficulty=0.6, glare=True),
     {"medication": "telmi", "title": "Telmisartan, with flash glare", "hint": "Glare on the foil. Pockets under it are not guessed."}),
    ("metformin_dose1.jpg", METF, {0}, 26, dict(difficulty=0.6),
     {"medication": "metf", "title": "Metformin, after the 8:30 AM dose", "hint": "Try it while Telmisartan is the expected medicine: expect 'wrong strip'."}),
    ("unregistered_strip.jpg", OTHER, set(), 27, dict(difficulty=0.5),
     {"medication": None, "title": "A strip that was never registered", "hint": "Expect: not recognised."}),
]


def main() -> int:
    OUT.mkdir(exist_ok=True)
    samples = []
    for name, spec, popped, seed, kw, meta in SHOTS:
        img = synth.make_shot(spec, popped, seed=seed, **kw).image
        cv.imwrite(str(OUT / name), img, [cv.IMWRITE_JPEG_QUALITY, 88])
        if meta:
            samples.append({"id": Path(name).stem, "file": name, **meta})
    manifest = {"version": 1, "medications": MEDICATIONS, "samples": samples,
                "note": "Synthetic photos generated by scripts/make_demo_assets.py. Real photos may replace any file."}
    (OUT / "manifest.json").write_text(json.dumps(manifest, indent=2))
    print(f"wrote {len(SHOTS)} images and manifest.json to {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
